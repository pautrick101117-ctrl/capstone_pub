CREATE OR REPLACE FUNCTION public.bgy_nov2_guard_document_pickup()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
BEGIN
  IF NEW.status='ready_for_pickup' AND OLD.status IS DISTINCT FROM NEW.status THEN
    IF NEW.pickup_scheduled_for IS NULL OR NEW.pickup_scheduled_for <= now() THEN
      RAISE EXCEPTION 'Set a future document pickup date and time before marking it ready.' USING ERRCODE='23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS bgy_nov2_document_pickup_required ON public.requests;
CREATE TRIGGER bgy_nov2_document_pickup_required BEFORE UPDATE OF status ON public.requests
  FOR EACH ROW EXECUTE FUNCTION public.bgy_nov2_guard_document_pickup();

CREATE OR REPLACE FUNCTION public.bgy_nov2_schedule_document_pickup(
 p_request uuid,p_actor uuid,p_version integer,p_when timestamptz,p_instructions text,p_operation uuid
) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE doc public.requests%ROWTYPE; person public.users%ROWTYPE; output jsonb; message text;
BEGIN
 SELECT * INTO person FROM public.users WHERE id=p_actor AND role IN ('admin','super_admin') AND is_active=true;
 IF NOT FOUND THEN RAISE EXCEPTION 'Administrator required' USING ERRCODE='42501'; END IF;
 SELECT * INTO doc FROM public.requests WHERE id=p_request FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Request not found' USING ERRCODE='P0002'; END IF;
 IF doc.status NOT IN ('document_prepared','ready_for_pickup') THEN
  RAISE EXCEPTION 'Prepare the document before assigning its pickup schedule.' USING ERRCODE='23514'; END IF;
 IF doc.lock_version IS DISTINCT FROM p_version THEN
  RAISE EXCEPTION 'Request changed. Reload and try again.' USING ERRCODE='40001'; END IF;
 IF p_when IS NULL OR p_when <= now() THEN
  RAISE EXCEPTION 'Choose a future date and time for pickup.' USING ERRCODE='23514'; END IF;
 IF length(coalesce(p_instructions,'')) > 700 THEN RAISE EXCEPTION 'Pickup instructions are too long.' USING ERRCODE='23514'; END IF;
 IF p_operation IS NULL OR EXISTS(SELECT 1 FROM public.case_history_events WHERE operation_id=p_operation) THEN
  RAISE EXCEPTION 'This operation was already saved.' USING ERRCODE='23505'; END IF;
 IF doc.pickup_scheduled_for IS NOT DISTINCT FROM p_when AND coalesce(doc.pickup_instructions,'')=coalesce(btrim(p_instructions),'') THEN
  RAISE EXCEPTION 'Pickup schedule is unchanged.' USING ERRCODE='23514'; END IF;
 UPDATE public.requests SET pickup_scheduled_for=p_when,pickup_instructions=btrim(coalesce(p_instructions,'')),
  lock_version=lock_version+1,updated_at=now() WHERE id=p_request RETURNING to_jsonb(requests.*) INTO output;
 message := 'Barangay document pickup scheduled for ' || to_char(p_when AT TIME ZONE 'Asia/Manila','Mon DD, YYYY HH12:MI AM') || ' (Philippine time).';
 INSERT INTO public.case_history_events(entity_type,entity_id,event_type,actor_id,actor_name_snapshot,actor_role,
  previous_status,new_status,message,visibility,operation_id)
 VALUES('request',p_request,'response_added',p_actor,coalesce(person.full_name,person.first_name),person.role,
  doc.status,doc.status,message,'resident',p_operation);
 INSERT INTO public.request_timeline(request_id,status,note) VALUES(p_request,doc.status,message);
 IF doc.status='ready_for_pickup' THEN
   INSERT INTO public.notifications(user_id,title,body,kind,broadcast)
   VALUES(doc.user_id,'Updated document pickup schedule',message,'info',false);
 END IF;
 RETURN output;
END $$;
REVOKE ALL ON FUNCTION public.bgy_nov2_schedule_document_pickup(uuid,uuid,integer,timestamptz,text,uuid)
 FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.bgy_nov2_schedule_document_pickup(uuid,uuid,integer,timestamptz,text,uuid) TO service_role;

-- Phase 9 approval guard correction: borrowed, unreturned resources remain
-- occupied even when their originally promised due time has already passed.
-- Replaces the guard body only; does not touch any booking/history records.
CREATE OR REPLACE FUNCTION public.bgy_phase9_request_guard()
RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,public AS $$
DECLARE v_asset public.borrowable_assets%ROWTYPE; v_reserved bigint; v_now timestamptz := clock_timestamp();
BEGIN
  IF TG_OP='INSERT' THEN
    SELECT * INTO v_asset FROM public.borrowable_assets WHERE id=NEW.asset_id FOR SHARE;
    IF NOT FOUND OR NOT v_asset.is_active THEN
      RAISE EXCEPTION 'BGY_BORROW_RESOURCE_UNAVAILABLE' USING ERRCODE='23514';
    END IF;
    IF v_asset.max_borrow_minutes IS NULL THEN
      RAISE EXCEPTION 'BGY_BORROW_DURATION_NOT_CONFIGURED' USING ERRCODE='23514';
    END IF;
    IF NEW.due_at <= NEW.start_at OR NEW.start_at < v_now - interval '5 minutes' THEN
      RAISE EXCEPTION 'BGY_BORROW_INVALID_DATES' USING ERRCODE='22023';
    END IF;
    IF extract(epoch from (NEW.due_at-NEW.start_at)) > v_asset.max_borrow_minutes * 60 THEN
      RAISE EXCEPTION 'BGY_BORROW_DURATION_EXCEEDED' USING ERRCODE='23514';
    END IF;
    IF NEW.quantity < 1 OR (v_asset.category='facility' AND NEW.quantity<>1)
       OR NEW.quantity>v_asset.total_quantity THEN
      RAISE EXCEPTION 'BGY_BORROW_INVALID_QUANTITY' USING ERRCODE='22023';
    END IF;
    NEW.max_duration_minutes_at_submission := v_asset.max_borrow_minutes;
    -- Pending requests do not reserve inventory. A separate check occurs during approval.
  ELSIF OLD.status='pending' AND NEW.status='approved' THEN
    SELECT * INTO v_asset FROM public.borrowable_assets WHERE id=NEW.asset_id FOR UPDATE;
    IF NOT FOUND OR NOT v_asset.is_active THEN
      RAISE EXCEPTION 'BGY_BORROW_RESOURCE_UNAVAILABLE' USING ERRCODE='23514';
    END IF;
    IF NEW.due_at <= v_now THEN
      RAISE EXCEPTION 'BGY_BORROW_WINDOW_EXPIRED' USING ERRCODE='23514';
    END IF;
    -- Keep an overdue but unreturned item blocked until staff records its return.
    -- Do not apply a newer maximum retroactively: submitted terms remain authoritative.
    SELECT coalesce(sum(r.quantity),0) INTO v_reserved FROM public.borrowing_requests r
    WHERE r.asset_id=NEW.asset_id AND r.id<>NEW.id
      AND r.status IN ('approved','borrowed')
      AND r.start_at<NEW.due_at AND (r.due_at>NEW.start_at OR r.status='borrowed');
    IF v_reserved + NEW.quantity > v_asset.total_quantity THEN
      RAISE EXCEPTION 'BGY_BORROW_OVERBOOKED' USING ERRCODE='23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;

CREATE OR REPLACE FUNCTION public.bgy_nov2_ready() RETURNS boolean LANGUAGE sql STABLE AS $$
 SELECT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='requests' AND column_name='pickup_scheduled_for')
 AND EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='census_households' AND column_name='is_archived')
 AND to_regprocedure('public.bgy_nov2_schedule_document_pickup(uuid,uuid,integer,timestamptz,text,uuid)') IS NOT NULL;
$$;
REVOKE ALL ON FUNCTION public.bgy_nov2_ready() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.bgy_nov2_ready() TO service_role;
