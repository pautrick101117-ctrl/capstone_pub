-- Actual ID pickup bookings are serialized on the requested pickup slot row.
-- This protects against two residents simultaneously taking the final place.
CREATE OR REPLACE FUNCTION public.bgy_nov2_validate_id_pickup()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE s public.id_pickup_slots%ROWTYPE; busy integer; local_date date;
BEGIN
  IF NEW.status NOT IN ('submitted','confirmed','rescheduled') THEN RETURN NEW; END IF;
  -- Existing unscheduled legacy rows remain editable without silently inventing an appointment.
  IF TG_OP='UPDATE' AND NEW.preferred_date IS NULL AND OLD.preferred_date IS NULL
     AND NEW.time_slot IS NULL AND OLD.time_slot IS NULL THEN RETURN NEW; END IF;
  IF NEW.preferred_date IS NULL OR nullif(btrim(NEW.time_slot),'') IS NULL THEN
    RAISE EXCEPTION 'Choose an available Barangay ID pickup date and time.' USING ERRCODE='23514';
  END IF;
  local_date := (now() AT TIME ZONE 'Asia/Manila')::date;
  IF NEW.preferred_date < local_date THEN
    RAISE EXCEPTION 'Past pickup dates are not available.' USING ERRCODE='23514';
  END IF;
  SELECT * INTO s FROM public.id_pickup_slots
    WHERE slot_date=NEW.preferred_date AND time_slot=NEW.time_slot AND is_active=true FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'That ID pickup schedule is unavailable. Select an active slot.' USING ERRCODE='23514';
  END IF;
  IF NEW.preferred_date=local_date AND split_part(s.time_slot,' - ',1) ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'
     AND split_part(s.time_slot,' - ',1)::time <= (now() AT TIME ZONE 'Asia/Manila')::time THEN
    RAISE EXCEPTION 'This pickup time has already passed.' USING ERRCODE='23514';
  END IF;
  SELECT count(*) INTO busy FROM public.id_requests r
    WHERE r.preferred_date=s.slot_date AND r.time_slot=s.time_slot
      AND r.status IN ('submitted','confirmed','rescheduled') AND r.id IS DISTINCT FROM NEW.id;
  IF busy >= s.capacity THEN
    RAISE EXCEPTION 'This pickup schedule is full. Choose another time.' USING ERRCODE='23514';
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS bgy_nov2_id_slot_capacity ON public.id_requests;
CREATE TRIGGER bgy_nov2_id_slot_capacity BEFORE INSERT OR UPDATE OF preferred_date,time_slot,status
  ON public.id_requests FOR EACH ROW EXECUTE FUNCTION public.bgy_nov2_validate_id_pickup();

CREATE OR REPLACE FUNCTION public.bgy_nov2_validate_slot_capacity()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path=public AS $$
DECLARE busy integer;
BEGIN
  IF NEW.capacity < 1 THEN RAISE EXCEPTION 'Capacity must be at least 1' USING ERRCODE='23514'; END IF;
  IF OLD.slot_date IS DISTINCT FROM NEW.slot_date OR OLD.time_slot IS DISTINCT FROM NEW.time_slot THEN
    IF EXISTS(SELECT 1 FROM public.id_requests r WHERE r.preferred_date=OLD.slot_date
      AND r.time_slot=OLD.time_slot AND r.status IN ('submitted','confirmed','rescheduled')) THEN
      RAISE EXCEPTION 'Cannot move a pickup slot with active appointments; deactivate it and create another.' USING ERRCODE='23514';
    END IF;
  ELSE
    SELECT count(*) INTO busy FROM public.id_requests r WHERE r.preferred_date=NEW.slot_date
      AND r.time_slot=NEW.time_slot AND r.status IN ('submitted','confirmed','rescheduled');
    IF NEW.capacity < busy THEN
      RAISE EXCEPTION 'Slot capacity cannot be lower than active appointments.' USING ERRCODE='23514';
    END IF;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS bgy_nov2_id_slot_edit_guard ON public.id_pickup_slots;
CREATE TRIGGER bgy_nov2_id_slot_edit_guard BEFORE UPDATE ON public.id_pickup_slots
  FOR EACH ROW EXECUTE FUNCTION public.bgy_nov2_validate_slot_capacity();

-- Document pickup is assigned by staff and visible to the resident; never generated by the resident.
ALTER TABLE public.requests ADD COLUMN IF NOT EXISTS pickup_scheduled_for timestamptz;
